// 🎯 Centro da RPPN
const CENTER = [-14.777, -45.123];

// 🚨 Cria ícone personalizado para alarmes
const alertIcon = L.divIcon({
  className: 'custom-div-icon',
  html: `<div style="background-color:#ff0000;width:16px;height:16px;border-radius:50%;border:2px solid white;box-shadow:0 0 20px rgba(255,0,0,0.8);"></div>`,
  iconSize: [16, 16],
  iconAnchor: [8, 8],
});

function CameraMap({ eventos = [] }) {
  const mapRef = useRef(null);

  // 🔍 Ajusta o zoom para caber todo o perímetro
  useEffect(() => {
    if (mapRef.current) {
      const bounds = RPPN_PERIMETER;
      mapRef.current.fitBounds(bounds, { padding: [40, 40] });
    }
  }, []);

  // 🚨 Filtra apenas eventos CONFIRMED
  const alarmesAtivos = eventos.filter(e => e.status === 'CONFIRMED');

  return (
    <div className="painel" style={{ padding: '0', overflow: 'hidden', borderRadius: '10px' }}>
      <MapContainer
        ref={mapRef}
        center={CENTER}
        zoom={13}
        style={{ height: '500px', width: '100%' }}
        scrollWheelZoom={true}
      >
        {/* 🛰️ MAPA SATÉLITE */}
        <TileLayer
          attribution='&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a>'
          url="https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}"
        />

        {/* 📍 Perímetro da RPPN */}
        <Polygon
          positions={RPPN_PERIMETER}
          pathOptions={{
            color: '#00ffff',
            weight: 3,
            fillColor: '#00ffff',
            fillOpacity: 0.1,
          }}
        />

        {/* 📍 Marcador central */}
        <Marker position={CENTER}>
          <Popup>
            <strong>🌳 RPPN - Reserva Particular</strong><br />
            Perímetro: {RPPN_PERIMETER.length} pontos
          </Popup>
        </Marker>

        {/* 🚨 Alarmes ativos */}
        {alarmesAtivos.map((evento, index) => (
          <Marker
            key={evento.id || index}
            position={[
              CENTER[0] + (Math.random() - 0.5) * 0.008,
              CENTER[1] + (Math.random() - 0.5) * 0.008
            ]}
            icon={alertIcon}
          >
            <Popup>
              <div>
                <strong>🚨 Alarme Ativo</strong><br />
                ID: #{evento.id}<br />
                Confiança: {(evento.confidence * 100).toFixed(0)}%<br />
                Horário: {new Date(evento.detected_at).toLocaleString('pt-BR')}
              </div>
            </Popup>
          </Marker>
        ))}

        {/* 📊 Legenda */}
        <div style={{
          position: 'absolute',
          bottom: 20,
          left: 20,
          backgroundColor: 'rgba(0,0,0,0.75)',
          color: 'white',
          padding: '10px 15px',
          borderRadius: 8,
          fontSize: 12,
          zIndex: 1000,
          backdropFilter: 'blur(4px)',
          fontFamily: 'system-ui, sans-serif'
        }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
            <span style={{ color: '#00ffff' }}>●</span> Perímetro RPPN
          </div>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
            <span style={{ color: '#ff0000' }}>●</span> {alarmesAtivos.length} alarme(s) ativo(s)
          </div>
        </div>
      </MapContainer>
    </div>
  );
}

export default CameraMap;
